#!/usr/bin/env python3
"""On-demand local ADP-Observatory launcher; standard-library only, no network calls.

This helper does NOT install software or attest executable provenance. It may
only be used with an existing executable approved by the user/environment.
Reports are generated by Observatory, outside the analyzed project.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
from typing import Optional

EXIT_NOT_INSTALLED = 3
EXIT_UNSAFE = 4
EXIT_FAILED = 5


def result(status: str, project: str, **kwargs: object) -> dict:
    return {"status": status, "project": project, **kwargs}


def emit(payload: dict) -> None:
    print(json.dumps(payload, ensure_ascii=False, sort_keys=True))


def is_within(path: Path, project: Path) -> bool:
    try:
        path.relative_to(project)
        return True
    except ValueError:
        return False


def executable_candidates(explicit: Optional[str]) -> list[Path]:
    if explicit:
        return [Path(explicit).expanduser()]
    candidates: list[Path] = []
    env_candidate = os.environ.get("ADP_OBSERVATORY_BIN")
    if env_candidate:
        candidates.append(Path(env_candidate).expanduser())

    localappdata = os.environ.get("LOCALAPPDATA")
    if localappdata:
        candidates.append(Path(localappdata) / "Programs" / "ADP-Observatory" / "adp-observatory.exe")
        candidates.append(Path(localappdata) / "ADP-Observatory" / "adp-observatory.exe")

    home = Path.home()
    candidates.extend([
        home / ".local" / "bin" / "adp-observatory",
        home / ".local" / "bin" / "adp-observatory.exe",
    ])
    on_path = shutil.which("adp-observatory")
    if on_path:
        candidates.append(Path(on_path))
    if os.name == "nt":
        on_path_exe = shutil.which("adp-observatory.exe")
        if on_path_exe:
            candidates.append(Path(on_path_exe))
    return candidates


def find_executable(project: Path, explicit: Optional[str]) -> tuple[Optional[Path], str]:
    if explicit and not Path(explicit).expanduser().is_absolute():
        return None, "--binary requires an absolute executable path"

    unsafe = False
    seen: set[Path] = set()
    for candidate in executable_candidates(explicit):
        # Never run from a relative PATH entry or a path resolving into target data.
        if not candidate.is_absolute():
            unsafe = True
            continue
        try:
            resolved = candidate.resolve(strict=True)
        except (OSError, RuntimeError):
            continue
        if resolved in seen:
            continue
        seen.add(resolved)
        if is_within(resolved, project):
            unsafe = True
            continue
        if resolved.is_file() and os.access(resolved, os.X_OK):
            return resolved, ""
    if unsafe:
        return None, "An executable candidate was rejected because its path was unsafe or inside the analyzed project"
    return None, "No approved, locally installed adp-observatory executable was found"


def alternate_installations(project: Path, selected: Path, explicit: Optional[str]) -> list[str]:
    """Surface duplicates without executing, updating or deleting them.

    Only considers already-discovered, executable files outside the target
    project. The caller can inspect them separately if version drift matters.
    """
    if explicit:
        return []
    alternatives: list[str] = []
    seen: set[Path] = {selected}
    for candidate in executable_candidates(None):
        if not candidate.is_absolute():
            continue
        try:
            resolved = candidate.resolve(strict=True)
        except (OSError, RuntimeError):
            continue
        if resolved in seen or is_within(resolved, project):
            continue
        seen.add(resolved)
        if resolved.is_file() and os.access(resolved, os.X_OK):
            alternatives.append(str(resolved))
        if len(alternatives) >= 8:
            break
    return alternatives


def browser_capable() -> bool:
    if os.environ.get("CI") or os.environ.get("SSH_CONNECTION") or os.environ.get("SSH_TTY"):
        return False
    if sys.platform.startswith("linux") and not (
        os.environ.get("DISPLAY") or os.environ.get("WAYLAND_DISPLAY")
    ):
        return False
    return True


def extract_scan_states(text: str) -> dict:
    """Read the *same run's* explicit status lines; never infer from file counts."""
    result: dict[str, object] = {}
    mapping = {
        "Work index status: ": "work_index_status",
        "Delivery metric state: ": "delivery_metric_state",
        "Work index errors: ": "work_index_error_count",
    }
    for line in text.splitlines():
        for prefix, key in mapping.items():
            if line.startswith(prefix):
                val = line[len(prefix):].strip()
                if key == "work_index_error_count":
                    if val.isdecimal():
                        result[key] = int(val)
                elif val in {"INVALID", "UNKNOWN", "STRUCTURALLY_VALID",
                             "UNSUPPORTED_SCHEMA", "KNOWN", "PARTIAL", "NOT_APPLICABLE"}:
                    result[key] = val
    return result


def extract_report_path(text: str) -> Optional[str]:
    for line in text.splitlines():
        prefix = "Local ADP report: "
        if line.startswith(prefix):
            return line[len(prefix):].strip() or None
    return None


def launch(project: Path, explicit: Optional[str], no_open: bool, timeout: int) -> tuple[dict, int]:
    project_str = str(project)
    binary, why = find_executable(project, explicit)
    if binary is None:
        status = "UNSAFE_EXECUTABLE" if "unsafe" in why.lower() or "requires an absolute" in why else "NOT_INSTALLED"
        return result(status, project_str, detail=why, installation_required=(status == "NOT_INSTALLED")), (
            EXIT_UNSAFE if status == "UNSAFE_EXECUTABLE" else EXIT_NOT_INSTALLED
        )

    alternatives = alternate_installations(project, binary, explicit)
    can_open = browser_capable() and not no_open
    argv = [str(binary), "dashboard", project_str]
    if not can_open:
        argv.append("--no-open")
    try:
        run = subprocess.run(
            argv, capture_output=True, text=True, encoding="utf-8",
            errors="replace", timeout=timeout, check=False,
        )
    except subprocess.TimeoutExpired:
        return result("EXECUTION_FAILED", project_str, detail="Observatory timed out",
                      executable=str(binary)), EXIT_FAILED
    except OSError as exc:
        return result("EXECUTION_FAILED", project_str, detail=str(exc),
                      executable=str(binary)), EXIT_FAILED

    path = extract_report_path(run.stdout)
    if run.returncode != 0:
        return result("EXECUTION_FAILED", project_str,
                      detail=(run.stderr or run.stdout).strip()[:1200],
                      executable=str(binary), report_path=path), EXIT_FAILED

    if not path or not Path(path).is_file():
        return result("EXECUTION_FAILED", project_str,
                      detail="No generated HTML report file could be confirmed",
                      executable=str(binary), report_path=path), EXIT_FAILED

    # Require a *positive* launch outcome from the executable. Earlier
    # versions returned exit 0 whenever a report was saved, even when no
    # browser could be opened, so absence of an error is not proof of launch.
    marker = next(
        (line.removeprefix("Browser launch: ").split(" ", 1)[0]
         for line in run.stdout.splitlines()
         if line.startswith("Browser launch: ")),
        "UNKNOWN",
    )
    if not can_open:
        marker = "NOT_REQUESTED"
    if marker == "REQUESTED" and can_open:
        status = "BROWSER_OPEN_REQUESTED"
        detail = "The OS accepted an open request; the user's browser visibility is NOT confirmed."
    else:
        status = "REPORT_SAVED"
        if marker == "FAILED":
            detail = "Opening the default browser failed. Open the local HTML report manually."
        elif not can_open:
            detail = "Browser opening is disabled or this is not a usable local desktop session."
        else:
            detail = "The executable did not confirm a browser-open request. Open the report manually; do not claim it appeared."
    return result(
        status, project_str, executable=str(binary), report_path=path,
        browser_open_attempted=can_open, browser_launch_status=marker,
        alternate_installations=alternatives,
        detail=detail,
        **extract_scan_states(run.stdout),
    ), 0


def main(argv: Optional[list[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project", default=".", help="Project directory to inspect")
    parser.add_argument("--binary", help="Absolute path to an explicitly trusted executable")
    parser.add_argument("--no-open", action="store_true",
                        help="Generate offline HTML without attempting to open a browser")
    parser.add_argument("--timeout", type=int, default=120,
                        help="Maximum seconds allowed for local analysis (1-600)")
    args = parser.parse_args(argv)

    if not 1 <= args.timeout <= 600:
        parser.error("--timeout must be between 1 and 600")
    try:
        project = Path(args.project).expanduser().resolve(strict=True)
    except (OSError, RuntimeError) as exc:
        emit(result("PROJECT_UNAVAILABLE", str(args.project), detail=str(exc)))
        return EXIT_UNSAFE
    if not project.is_dir():
        emit(result("PROJECT_UNAVAILABLE", str(project), detail="Project is not a directory"))
        return EXIT_UNSAFE

    payload, code = launch(project, args.binary, args.no_open, args.timeout)
    emit(payload)
    return code


if __name__ == "__main__":
    raise SystemExit(main())
